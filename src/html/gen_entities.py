#!/usr/bin/env python3
"""Generate src/html/entities_data.h from the WHATWG entities.json.

To regenerate the table, download https://html.spec.whatwg.org/entities.json
and run:

    python3 -I src/html/gen_entities.py entities.json > src/html/entities_data.h

The table holds each name once, without the leading '&' and trailing ';'.
Names are sorted bytewise and stored back to back in entity_names.
entity_off[i] is the offset of name i; its length is
entity_off[i + 1] - entity_off[i]. entity_val[i] packs:

    bits 0-16   first code point
    bits 17-20  index into entity_cp2 of the second code point (0: none)
    bit  21     the name also matches without a semicolon (legacy)
"""
import json
import sys


def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    names = {}
    for key, val in data.items():
        assert key[0] == "&"
        legacy = not key.endswith(";")
        name = key[1:].rstrip(";")
        cps = val["codepoints"]
        prev = names.get(name)
        if prev:
            assert prev[0] == cps
            names[name] = (cps, prev[1] or legacy)
        else:
            names[name] = (cps, legacy)

    order = sorted(names, key=lambda n: n.encode("ascii"))
    cp2_list = [0] + sorted({v[0][1] for v in names.values() if len(v[0]) > 1})
    assert len(cp2_list) <= 16

    blob = "".join(order)
    assert len(blob) < 65536
    offs = []
    vals = []
    pos = 0
    for n in order:
        cps, legacy = names[n]
        offs.append(pos)
        pos += len(n)
        assert cps[0] < (1 << 17)
        cp2 = cp2_list.index(cps[1]) if len(cps) > 1 else 0
        vals.append(cps[0] | (cp2 << 17) | ((1 if legacy else 0) << 21))
    offs.append(pos)

    out = sys.stdout
    out.write("/* Generated by gen_entities.py from the WHATWG entities.json. Do not edit. */\n")
    out.write("#define ENTITY_COUNT %d\n" % len(order))
    out.write("#define ENTITY_MAX_LEN %d\n" % max(len(n) for n in order))
    out.write("#define ENTITY_MAX_LEGACY_LEN %d\n" %
              max(len(n) for n in order if names[n][1]))
    out.write("static const uint32_t entity_cp2[%d] = {%s};\n" %
              (len(cp2_list), ", ".join("0x%X" % c for c in cp2_list)))
    out.write("static const char entity_names[] =\n")
    for i in range(0, len(blob), 72):
        out.write('    "%s"\n' % blob[i:i + 72])
    out.write("    ;\n")
    out.write("static const uint16_t entity_off[%d] = {\n" % len(offs))
    for i in range(0, len(offs), 12):
        out.write("    " + ", ".join(str(o) for o in offs[i:i + 12]) + ",\n")
    out.write("};\n")
    out.write("static const uint32_t entity_val[%d] = {\n" % len(vals))
    for i in range(0, len(vals), 8):
        out.write("    " + ", ".join("0x%X" % v for v in vals[i:i + 8]) + ",\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
