#!/usr/bin/env python3
"""Generate src/codec/brotli_dict_data.c: the brotli static dictionary.

The dictionary is the one in RFC 7932 Appendix A (122784 bytes, CRC-32
0x5136cb04). It comes from the brotli project (https://github.com/google/brotli,
MIT licence, "Copyright (c) 2009, 2010, 2013-2016 by the Brotli Authors").
This script takes it from a copy of that project's library already
installed on the build machine, which holds the dictionary as one data
block, and does not download anything. The data in the committed file was
extracted from Homebrew's brotli 1.2.0:

    python3 -I src/codec/gen_brotli_dict.py \\
        /opt/homebrew/Cellar/brotli/1.2.0/lib/libbrotlicommon.1.2.0.dylib \\
        > src/codec/brotli_dict_data.c

The library file is only read as bytes. The script finds the dictionary by
the start of its text, checks its length and its CRC-32 against the RFC's
values, and stores it zlib-compressed so it
costs less in the application; au_brotli_dict_new inflates it.
"""
import sys
import zlib

DICT_SIZE = 122784
DICT_CRC = 0x5136CB04
START = (b"timedownlifeleftbackcodedatashowonlysitecityopenjustlikefreeworktext"
         b"yearoverbodyloveformbookplaylivelinehelphomesidemorewordlongthemview")


def main():
    data = open(sys.argv[1], "rb").read()
    at = data.find(START)
    if at < 0 or data.find(START, at + 1) >= 0:
        sys.exit("dictionary start not found exactly once")
    d = data[at:at + DICT_SIZE]
    if len(d) != DICT_SIZE or zlib.crc32(d) != DICT_CRC:
        sys.exit("dictionary length or CRC-32 does not match RFC 7932")
    z = zlib.compress(d, 9)
    assert zlib.decompress(z) == d

    out = sys.stdout
    out.write("/* Generated by gen_brotli_dict.py. Do not edit.\n"
              " *\n"
              " * The brotli static dictionary (RFC 7932 Appendix A), zlib-compressed.\n"
              " * From the brotli project, MIT licence; see gen_brotli_dict.py. */\n")
    out.write('#include "brotli.h"\n\n')
    out.write("#define DICT_CRC 0x%08Xu\n\n" % DICT_CRC)
    out.write("static const uint8_t dict_z[%d] = {\n" % len(z))
    for i in range(0, len(z), 16):
        out.write("    " + ",".join("%d" % c for c in z[i:i + 16]) + ",\n")
    out.write("};\n\n")
    out.write("""struct AuBrotliDict {
    uint8_t *bytes;
};

AuBrotliDict *au_brotli_dict_new(void)
{
    uint8_t *bytes;
    size_t len;
    AuBrotliDict *d;
    if (!au_inflate_all(AU_INFLATE_ZLIB, dict_z, sizeof dict_z, AU_BROTLI_DICT_SIZE, &bytes, &len))
        return NULL;
    if (len != AU_BROTLI_DICT_SIZE || au_crc32(0, bytes, len) != DICT_CRC) {
        au_free(bytes);
        return NULL;
    }
    d = au_alloc(sizeof *d);
    d->bytes = bytes;
    return d;
}

void au_brotli_dict_free(AuBrotliDict *d)
{
    if (!d)
        return;
    au_free(d->bytes);
    au_free(d);
}

const uint8_t *au_brotli_dict_bytes(const AuBrotliDict *d) { return d->bytes; }
""")


if __name__ == "__main__":
    main()
