#!/usr/bin/env python3
"""Generates src/net/psl_data.c from the Public Suffix List.

Usage: python3 -I src/net/gen_psl.py public_suffix_list.dat > src/net/psl_data.c

The list comes from https://publicsuffix.org/list/public_suffix_list.dat
(the raw list is not kept in git). Each rule's labels are lower-cased,
IDN labels are Punycode-encoded ("xn--..."), and the labels are reversed
("co.uk" -> "uk.co") so that rules sharing a top-level domain sort
together. Rules "*.x" and "!e.x" become flags on the entry for "x" and
"x.e" (reversed) respectively.

Table format (au_psl_data, see psl.c):
    entries sorted by reversed name (bytewise), in blocks of BLOCK;
    each entry: flags (1 byte: 1 rule, 2 wildcard children, 4 exception),
                shared prefix length with the previous entry in the block
                (1 byte; 0 for a block's first entry),
                suffix length (1 byte), suffix bytes;
    au_psl_blocks[i] is the byte offset of block i.
The list's date (the newest "VERSION"/"COMMIT" line, or the file's
modification time) is recorded in AU_PSL_DATE.
"""
import os
import sys
import time

BLOCK = 32


def label_ascii(label):
    if all(ord(c) < 128 for c in label):
        return label
    return "xn--" + label.encode("punycode").decode("ascii")


def main():
    path = sys.argv[1]
    with open(path, encoding="utf-8") as f:
        text = f.read()
    date = None
    entries = {}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("// VERSION:") or line.startswith("// COMMIT:"):
            date = date or line.split(":", 1)[1].strip()
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0].lower()
        flag = 1
        if rule.startswith("!"):
            flag = 4
            rule = rule[1:]
        elif rule.startswith("*."):
            flag = 2
            rule = rule[2:]
        elif "*" in rule:
            continue  # wildcards only as the leftmost label are supported
        labels = [label_ascii(l) for l in rule.split(".")]
        key = ".".join(reversed(labels))
        entries[key] = entries.get(key, 0) | flag
    if not date:
        date = time.strftime("%Y-%m-%d", time.gmtime(os.path.getmtime(path)))
    keys = sorted(entries, key=lambda k: k.encode("ascii"))
    data = bytearray()
    blocks = []
    prev = b""
    for i, k in enumerate(keys):
        kb = k.encode("ascii")
        if len(kb) > 255:
            raise SystemExit("rule too long: " + k)
        if i % BLOCK == 0:
            blocks.append(len(data))
            shared = 0
        else:
            shared = 0
            while shared < min(len(prev), len(kb), 255) and prev[shared] == kb[shared]:
                shared += 1
        data += bytes([entries[k], shared, len(kb) - shared]) + kb[shared:]
        prev = kb
    out = sys.stdout
    out.write("/* Generated by src/net/gen_psl.py from the Public Suffix List; do not edit.\n")
    out.write(" * List version: %s. %d rules, %d bytes of table, %d blocks. */\n" % (date, len(keys), len(data), len(blocks)))
    out.write('#include "psl.h"\n\n')
    out.write('const char au_psl_date[] = "%s";\n' % date)
    out.write("const uint32_t au_psl_count = %d;\n" % len(keys))
    out.write("const uint32_t au_psl_block_size = %d;\n" % BLOCK)
    out.write("const uint32_t au_psl_nblocks = %d;\n" % len(blocks))
    out.write("const uint32_t au_psl_data_len = %d;\n" % len(data))
    out.write("const uint32_t au_psl_blocks[] = {\n")
    for i in range(0, len(blocks), 10):
        out.write("    " + ", ".join(str(b) for b in blocks[i:i + 10]) + ",\n")
    out.write("};\n")
    out.write("const uint8_t au_psl_data[] = {\n")
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    out.write("};\n")


main()
